template <> bool I8085DAGToDAGISel::select<ISD::SETCC>(SDNode *N) {
  SDLoc dl(N);
  auto DL = CurDAG->getDataLayout();

  ISD::CondCode CC = cast<CondCodeSDNode>(N->getOperand(2))->get();

  SDValue Lhs = N->getOperand(0);
  SDValue Rhs = N->getOperand(1);
  SDValue Ops[] = {Lhs,Rhs};
  
  unsigned Opc=get8Opc(CC);

  if(Lhs.getSimpleValueType() == MVT::i16){
    Opc=get16Opc(CC);
  }
  else if(Lhs.getSimpleValueType() == MVT::i32){
    Opc=get32Opc(CC);
  }

  if (Opc == 0)
    return false;

  SDNode *ResNode=CurDAG->getMachineNode(Opc, dl,MVT::i8,Ops);
  ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
  CurDAG->RemoveDeadNode(N);
  return true;
}


template <> bool I8085DAGToDAGISel::select<ISD::BR_CC>(SDNode *N) {
  SDLoc dl(N);
  auto DL = CurDAG->getDataLayout();

  ISD::CondCode CC = cast<CondCodeSDNode>(N->getOperand(1))->get();

  SDValue Chain = N->getOperand(0);
  SDValue LHS = N->getOperand(2);
  SDValue RHS = N->getOperand(3);
  SDValue JumpTo = N->getOperand(4);

  // Fused compare-immediate-and-branch for i8 with constant RHS.
  // Bypasses the SET_*_8 diamond + JMP_8_IF path entirely.
  if (LHS.getSimpleValueType() == MVT::i8) {
    ConstantSDNode *RHSC = dyn_cast<ConstantSDNode>(RHS);
    if (!RHSC) {
      if (auto *LHSC = dyn_cast<ConstantSDNode>(LHS)) {
        CC = ISD::getSetCCSwappedOperands(CC);
        std::swap(LHS, RHS);
        RHSC = LHSC;
      }
    }

    if (RHSC) {
      unsigned FusedOpc = 0;
      uint64_t Imm = RHSC->getZExtValue() & 0xFF;

      switch (CC) {
      case ISD::SETEQ:  FusedOpc = I8085::BR_CC_EQ_8_IMM; break;
      case ISD::SETNE:  FusedOpc = I8085::BR_CC_NE_8_IMM; break;
      case ISD::SETULT: FusedOpc = I8085::BR_CC_ULT_8_IMM; break;
      case ISD::SETUGE: FusedOpc = I8085::BR_CC_UGE_8_IMM; break;
      case ISD::SETUGT:
        if (Imm < 255) { FusedOpc = I8085::BR_CC_UGE_8_IMM; Imm++; }
        break;
      case ISD::SETULE:
        if (Imm < 255) { FusedOpc = I8085::BR_CC_ULT_8_IMM; Imm++; }
        break;
      // Sign test against 0 is a pure S-flag branch (ORA A ; JM/JP), cheaper
      // than the bias sequence.
      case ISD::SETLT:
        if (Imm == 0) FusedOpc = I8085::BR_CC_MINUS_8;
        else { FusedOpc = I8085::BR_CC_SLT_8_IMM; Imm ^= 0x80; }
        break;
      case ISD::SETGE:
        if (Imm == 0) FusedOpc = I8085::BR_CC_PLUS_8;
        else { FusedOpc = I8085::BR_CC_SGE_8_IMM; Imm ^= 0x80; }
        break;
      case ISD::SETGT:
        // a > -1 == a >= 0 is a sign test (LLVM often canonicalizes `a >= 0`
        // to this form for i8).
        if (Imm == 0xFF) FusedOpc = I8085::BR_CC_PLUS_8;
        else if ((int8_t)Imm != 127) {
          FusedOpc = I8085::BR_CC_SGE_8_IMM; Imm = ((Imm + 1) & 0xFF) ^ 0x80;
        }
        break;
      case ISD::SETLE:
        // a <= -1 == a < 0 is a sign test (canonical form of i8 `a < 0`).
        if (Imm == 0xFF) FusedOpc = I8085::BR_CC_MINUS_8;
        else if ((int8_t)Imm != 127) {
          FusedOpc = I8085::BR_CC_SLT_8_IMM; Imm = ((Imm + 1) & 0xFF) ^ 0x80;
        }
        break;
      default: break;
      }

      if (FusedOpc) {
        bool IsSignTest = (FusedOpc == I8085::BR_CC_MINUS_8 ||
                           FusedOpc == I8085::BR_CC_PLUS_8);
        SDNode *Res;
        if (IsSignTest) {
          SDValue Ops[] = {LHS, JumpTo, Chain};
          Res = CurDAG->getMachineNode(FusedOpc, dl, MVT::Other, Ops);
        } else {
          SDValue ImmOp = CurDAG->getTargetConstant(Imm, dl, MVT::i8);
          SDValue Ops[] = {LHS, ImmOp, JumpTo, Chain};
          Res = CurDAG->getMachineNode(FusedOpc, dl, MVT::Other, Ops);
        }
        ReplaceUses(SDValue(N, 0), SDValue(Res, 0));
        CurDAG->RemoveDeadNode(N);
        return true;
      }
    }
  }

  // Fused compare-register-and-branch for i8 with a register RHS. Bypasses the
  // SET_*_8 boolean diamond + JMP_8_IF re-test for `if (a <cc> b)`. Unsigned and
  // equality use a plain SUB; signed use the sign-bias custom inserter. Only
  // register operands are fused: a constant would need materializing anyway, and
  // constant unsigned/equality cases are already handled by the *_IMM path
  // above, so here a constant simply falls through to the diamond.
  if (LHS.getSimpleValueType() == MVT::i8 &&
      !isa<ConstantSDNode>(LHS) && !isa<ConstantSDNode>(RHS)) {
    unsigned FusedOpc = 0;
    switch (CC) {
    case ISD::SETEQ:  FusedOpc = I8085::BR_CC_EQ_8; break;
    case ISD::SETNE:  FusedOpc = I8085::BR_CC_NE_8; break;
    case ISD::SETULT: FusedOpc = I8085::BR_CC_ULT_8; break;
    case ISD::SETUGE: FusedOpc = I8085::BR_CC_UGE_8; break;
    // a > b  <=>  b < a ;  a <= b  <=>  b >= a  (swap operands).
    case ISD::SETUGT: FusedOpc = I8085::BR_CC_ULT_8; std::swap(LHS, RHS); break;
    case ISD::SETULE: FusedOpc = I8085::BR_CC_UGE_8; std::swap(LHS, RHS); break;
    case ISD::SETLT:  FusedOpc = I8085::BR_CC_SLT_8; break;
    case ISD::SETGE:  FusedOpc = I8085::BR_CC_SGE_8; break;
    case ISD::SETGT:  FusedOpc = I8085::BR_CC_SLT_8; std::swap(LHS, RHS); break;
    case ISD::SETLE:  FusedOpc = I8085::BR_CC_SGE_8; std::swap(LHS, RHS); break;
    default: break;
    }
    if (FusedOpc) {
      SDValue Ops[] = {LHS, RHS, JumpTo, Chain};
      SDNode *Res = CurDAG->getMachineNode(FusedOpc, dl, MVT::Other, Ops);
      ReplaceUses(SDValue(N, 0), SDValue(Res, 0));
      CurDAG->RemoveDeadNode(N);
      return true;
    }
  }

  // Fused compare-against-constant-and-branch for i16. Byte-level SUI/SBI, XRI
  // combine, or high-byte bias against the immediate - no diamond, no register
  // materialization of the constant.
  //
  // The i16 fused inserters extract operand bytes with subreg COPYs, which the
  // fast register allocator (-O0) mishandles for a value carried across a loop
  // back-edge ("reading vreg without def"). The greedy allocator (-O1+) is
  // fine, so gate i16 fusion off at -O0 and let it use the diamond there.
  if (LHS.getSimpleValueType() == MVT::i16 &&
      OptLevel != CodeGenOptLevel::None) {
    ConstantSDNode *RHSC = dyn_cast<ConstantSDNode>(RHS);
    if (!RHSC) {
      if (auto *LHSC = dyn_cast<ConstantSDNode>(LHS)) {
        CC = ISD::getSetCCSwappedOperands(CC);
        std::swap(LHS, RHS);
        RHSC = LHSC;
      }
    }
    if (RHSC) {
      unsigned FusedOpc = 0;
      uint64_t Imm = RHSC->getZExtValue() & 0xFFFF;
      switch (CC) {
      case ISD::SETEQ:  FusedOpc = I8085::BR_CC_EQ_16_IMM; break;
      case ISD::SETNE:  FusedOpc = I8085::BR_CC_NE_16_IMM; break;
      case ISD::SETULT: FusedOpc = I8085::BR_CC_ULT_16_IMM; break;
      case ISD::SETUGE: FusedOpc = I8085::BR_CC_UGE_16_IMM; break;
      case ISD::SETUGT:
        if (Imm != 0xFFFF) { FusedOpc = I8085::BR_CC_UGE_16_IMM; Imm++; }
        break;
      case ISD::SETULE:
        if (Imm != 0xFFFF) { FusedOpc = I8085::BR_CC_ULT_16_IMM; Imm++; }
        break;
      case ISD::SETLT:  FusedOpc = I8085::BR_CC_SLT_16_IMM; break;
      case ISD::SETGE:  FusedOpc = I8085::BR_CC_SGE_16_IMM; break;
      case ISD::SETGT:
        if ((int16_t)Imm != 32767) {
          FusedOpc = I8085::BR_CC_SGE_16_IMM; Imm = (Imm + 1) & 0xFFFF;
        }
        break;
      case ISD::SETLE:
        if ((int16_t)Imm != 32767) {
          FusedOpc = I8085::BR_CC_SLT_16_IMM; Imm = (Imm + 1) & 0xFFFF;
        }
        break;
      default: break;
      }
      if (FusedOpc) {
        SDValue ImmOp = CurDAG->getTargetConstant(Imm, dl, MVT::i16);
        SDValue Ops[] = {LHS, ImmOp, JumpTo, Chain};
        SDNode *Res = CurDAG->getMachineNode(FusedOpc, dl, MVT::Other, Ops);
        ReplaceUses(SDValue(N, 0), SDValue(Res, 0));
        CurDAG->RemoveDeadNode(N);
        return true;
      }
    }
  }

  // Fused compare-register-and-branch for i16 (all condition codes). Bypasses
  // the SET_*_16 boolean diamond + JMP_8_IF re-test. Register operands only; a
  // constant operand falls through to the diamond, which materializes it.
  // (Gated off at -O0, see the i16-immediate note above.)
  if (LHS.getSimpleValueType() == MVT::i16 &&
      OptLevel != CodeGenOptLevel::None &&
      !isa<ConstantSDNode>(LHS) && !isa<ConstantSDNode>(RHS)) {
    unsigned FusedOpc = 0;
    switch (CC) {
    case ISD::SETEQ:  FusedOpc = I8085::BR_CC_EQ_16; break;
    case ISD::SETNE:  FusedOpc = I8085::BR_CC_NE_16; break;
    case ISD::SETULT: FusedOpc = I8085::BR_CC_ULT_16; break;
    case ISD::SETUGE: FusedOpc = I8085::BR_CC_UGE_16; break;
    case ISD::SETUGT: FusedOpc = I8085::BR_CC_ULT_16; std::swap(LHS, RHS); break;
    case ISD::SETULE: FusedOpc = I8085::BR_CC_UGE_16; std::swap(LHS, RHS); break;
    case ISD::SETLT:  FusedOpc = I8085::BR_CC_SLT_16; break;
    case ISD::SETGE:  FusedOpc = I8085::BR_CC_SGE_16; break;
    case ISD::SETGT:  FusedOpc = I8085::BR_CC_SLT_16; std::swap(LHS, RHS); break;
    case ISD::SETLE:  FusedOpc = I8085::BR_CC_SGE_16; std::swap(LHS, RHS); break;
    default: break;
    }
    if (FusedOpc) {
      SDValue Ops[] = {LHS, RHS, JumpTo, Chain};
      SDNode *Res = CurDAG->getMachineNode(FusedOpc, dl, MVT::Other, Ops);
      ReplaceUses(SDValue(N, 0), SDValue(Res, 0));
      CurDAG->RemoveDeadNode(N);
      return true;
    }
  }

  // Fall back to SET_* + JMP_8_IF for non-constant, i16, i32, or signed.
  unsigned Opc=get8Opc(CC);
  unsigned JumpOpc=I8085::JMP_8_IF;

  if(LHS.getSimpleValueType() == MVT::i16){
    Opc=get16Opc(CC);
  }
  else if(LHS.getSimpleValueType() == MVT::i32){
    Opc=get32Opc(CC);
  }

  SDNode *SETccNode=CurDAG->getMachineNode(Opc, dl,MVT::i8,{LHS,RHS});

  SDValue Ops[] = {SDValue(SETccNode, 0),JumpTo,Chain};

  SDNode *ResNode = CurDAG->getMachineNode(JumpOpc, dl,MVT::Other,Ops);
  ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
  CurDAG->RemoveDeadNode(N);
  return true;
}

template <> bool I8085DAGToDAGISel::select<ISD::BRCOND>(SDNode *N) {
  SDLoc dl(N);

  SDValue Chain = N->getOperand(0);
  SDValue Cond = N->getOperand(1);
  SDValue JumpTo = N->getOperand(2);

  if (Cond.getSimpleValueType() != MVT::i8)
    Cond = CurDAG->getZExtOrTrunc(Cond, dl, MVT::i8);

  SDValue Ops[] = {Cond, JumpTo, Chain};
  SDNode *ResNode =
      CurDAG->getMachineNode(I8085::JMP_8_IF, dl, MVT::Other, Ops);
  ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
  CurDAG->RemoveDeadNode(N);
  return true;
}

template <> bool I8085DAGToDAGISel::select<ISD::BRIND>(SDNode *N) {
  SDValue Chain = N->getOperand(0);
  SDValue Dest = N->getOperand(1);

  SDLoc DL(N);
  Chain = CurDAG->getCopyToReg(Chain, DL, I8085::HL, Dest);
  SDNode *ResNode = CurDAG->getMachineNode(I8085::PCHL, DL, MVT::Other, Chain);

  ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
  CurDAG->RemoveDeadNode(N);
  return true;
}

template <> bool I8085DAGToDAGISel::select<ISD::SHL>(SDNode *N) {
  SDLoc dl(N);
  auto DL = CurDAG->getDataLayout();

  SDValue LHS = N->getOperand(0);
  SDValue RHS = N->getOperand(1);


  if(LHS.getSimpleValueType() == MVT::i16){
    // Handle constant shift amounts with inline shifts (up to 8)
    if (const auto *C = dyn_cast<ConstantSDNode>(RHS)) {
      uint64_t ShiftAmt = C->getZExtValue();
      if (ShiftAmt == 1) {
        // Shift by 1 can be done with ADD
        SDValue Ops[] = {LHS, LHS};
        SDNode *ResNode = CurDAG->getMachineNode(I8085::ADD_16, dl, MVT::i16, Ops);
        ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
        CurDAG->RemoveDeadNode(N);
        return true;
      }
      if (ShiftAmt > 1 && ShiftAmt < 16) {
        SDValue Result = LHS;
        if (ShiftAmt >= 8) {
          Result = SDValue(CurDAG->getMachineNode(I8085::SHL_16_BY_8, dl, MVT::i16, Result), 0);
          ShiftAmt -= 8;
        }
        for (uint64_t i = 0; i < ShiftAmt; ++i) {
          SDValue Ops[] = {Result};
          Result = SDValue(CurDAG->getMachineNode(I8085::RL_16, dl, MVT::i16, Ops), 0);
        }
        ReplaceUses(SDValue(N, 0), Result);
        CurDAG->RemoveDeadNode(N);
        return true;
      }
    }
    SDValue Amt = RHS;
    if (Amt.getSimpleValueType() != MVT::i8)
      Amt = CurDAG->getZExtOrTrunc(Amt, dl, MVT::i8);
    unsigned Opc = I8085::SHL_16;
    SDValue Ops[] = {LHS, Amt};
    SDNode *ResNode = CurDAG->getMachineNode(Opc, dl, MVT::i16, Ops);
    ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
    CurDAG->RemoveDeadNode(N);
    return true;
  }
  if(LHS.getSimpleValueType() == MVT::i32){
    // Constant shifts: byte-shuffle + rotates (no limit on shift amount).
    // Variable shifts are lowered to __ashlsi3 libcall in LowerOperation.
    if (const auto *C = dyn_cast<ConstantSDNode>(RHS)) {
      uint64_t ShiftAmt = C->getZExtValue();
      if (ShiftAmt == 0) return false;
      SDValue Result = LHS;
      // Byte-shuffle for multiples of 8.
      if (ShiftAmt >= 24) {
        Result = SDValue(CurDAG->getMachineNode(I8085::SHL_32_BY_24, dl, MVT::i32, Result), 0);
        ShiftAmt -= 24;
      } else if (ShiftAmt >= 16) {
        Result = SDValue(CurDAG->getMachineNode(I8085::SHL_32_BY_16, dl, MVT::i32, Result), 0);
        ShiftAmt -= 16;
      } else if (ShiftAmt >= 8) {
        Result = SDValue(CurDAG->getMachineNode(I8085::SHL_32_BY_8, dl, MVT::i32, Result), 0);
        ShiftAmt -= 8;
      }
      // Remaining bits via rotate.
      for (uint64_t i = 0; i < ShiftAmt; ++i) {
        Result = SDValue(CurDAG->getMachineNode(I8085::RL_32, dl, MVT::i32, Result), 0);
      }
      ReplaceUses(SDValue(N, 0), Result);
      CurDAG->RemoveDeadNode(N);
      return true;
    }
    return false; // Variable shifts handled by LowerOperation libcall.
  }
  if(LHS.getSimpleValueType() == MVT::i8 && RHS.getSimpleValueType() == MVT::i8){
    // Handle constant shift amounts with inline shifts (up to 4)
    if (const auto *C = dyn_cast<ConstantSDNode>(RHS)) {
      uint64_t ShiftAmt = C->getZExtValue();
      if (ShiftAmt > 0 && ShiftAmt <= 4) {
        SDValue Result = LHS;
        for (uint64_t i = 0; i < ShiftAmt; ++i) {
          SDValue Ops[] = {Result};
          Result = SDValue(CurDAG->getMachineNode(I8085::RL_8, dl, MVT::i8, Ops), 0);
        }
        ReplaceUses(SDValue(N, 0), Result);
        CurDAG->RemoveDeadNode(N);
        return true;
      }
      // Amounts 5..7: branchless rotate-the-short-way + mask (no runtime loop).
      if (ShiftAmt >= 5 && ShiftAmt <= 7) {
        SDValue Ops[] = {LHS, CurDAG->getTargetConstant(ShiftAmt, dl, MVT::i8)};
        SDNode *Res = CurDAG->getMachineNode(I8085::SHL_8_HI, dl, MVT::i8, Ops);
        ReplaceUses(SDValue(N, 0), SDValue(Res, 0));
        CurDAG->RemoveDeadNode(N);
        return true;
      }
    }
    unsigned Opc=I8085::SHL_8;
    SDValue Ops[] = {LHS,RHS};
    SDNode *ResNode = CurDAG->getMachineNode(Opc, dl,MVT::i8,Ops);
    ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
    CurDAG->RemoveDeadNode(N);
    return true;
  }

  return false;
}

template <> bool I8085DAGToDAGISel::select<ISD::SRA>(SDNode *N) {
  SDLoc dl(N);
  auto DL = CurDAG->getDataLayout();

  SDValue LHS = N->getOperand(0);
  SDValue RHS = N->getOperand(1);


  if(LHS.getSimpleValueType() == MVT::i16){
    // Handle constant shift amounts with inline shifts
    if (const auto *C = dyn_cast<ConstantSDNode>(RHS)) {
      uint64_t ShiftAmt = C->getZExtValue();
      if (ShiftAmt > 0 && ShiftAmt < 16) {
        SDValue Result = LHS;
        if (ShiftAmt == 15) {
          // Sign extension: 0x0000 or 0xFFFF (5 insns instead of ~61)
          Result = SDValue(CurDAG->getMachineNode(I8085::SIGN_EXTEND_16, dl, MVT::i16, Result), 0);
          ReplaceUses(SDValue(N, 0), Result);
          CurDAG->RemoveDeadNode(N);
          return true;
        }
        if (ShiftAmt >= 8) {
          Result = SDValue(CurDAG->getMachineNode(I8085::ASR_16_BY_8, dl, MVT::i16, Result), 0);
          ShiftAmt -= 8;
        }
        for (uint64_t i = 0; i < ShiftAmt; ++i) {
          SDValue Ops[] = {Result};
          Result = SDValue(CurDAG->getMachineNode(I8085::ASR_16, dl, MVT::i16, Ops), 0);
        }
        ReplaceUses(SDValue(N, 0), Result);
        CurDAG->RemoveDeadNode(N);
        return true;
      }
    }
    SDValue Amt = RHS;
    if (Amt.getSimpleValueType() != MVT::i8)
      Amt = CurDAG->getZExtOrTrunc(Amt, dl, MVT::i8);
    unsigned Opc=I8085::SRA_16;
    SDValue Ops[] = {LHS,Amt};
    SDNode *ResNode = CurDAG->getMachineNode(Opc, dl,MVT::i16,Ops);
    ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
    CurDAG->RemoveDeadNode(N);
    return true;
  }
  if(LHS.getSimpleValueType() == MVT::i32){
    // Constant shifts: byte-shuffle + rotates.
    // Variable shifts are lowered to __ashrsi3 libcall in LowerOperation.
    if (const auto *C = dyn_cast<ConstantSDNode>(RHS)) {
      uint64_t ShiftAmt = C->getZExtValue();
      if (ShiftAmt == 0) return false;
      SDValue Result = LHS;
      // Byte-shuffle for multiples of 8.
      if (ShiftAmt >= 16) {
        Result = SDValue(CurDAG->getMachineNode(I8085::ASR_32_BY_16, dl, MVT::i32, Result), 0);
        ShiftAmt -= 16;
      } else if (ShiftAmt >= 8) {
        Result = SDValue(CurDAG->getMachineNode(I8085::ASR_32_BY_8, dl, MVT::i32, Result), 0);
        ShiftAmt -= 8;
      }
      // Remaining bits via arithmetic shift.
      for (uint64_t i = 0; i < ShiftAmt; ++i) {
        Result = SDValue(CurDAG->getMachineNode(I8085::ASR_32, dl, MVT::i32, Result), 0);
      }
      ReplaceUses(SDValue(N, 0), Result);
      CurDAG->RemoveDeadNode(N);
      return true;
    }
    return false; // Variable shifts handled by LowerOperation libcall.
  }
  if(LHS.getSimpleValueType() == MVT::i8 && RHS.getSimpleValueType() == MVT::i8){
    // Handle all constant shift amounts (1..7) with a straight-line unrolled
    // arithmetic-shift-right; only variable amounts fall to the runtime loop.
    if (const auto *C = dyn_cast<ConstantSDNode>(RHS)) {
      uint64_t ShiftAmt = C->getZExtValue();
      if (ShiftAmt > 0 && ShiftAmt <= 7) {
        SDValue Result = LHS;
        for (uint64_t i = 0; i < ShiftAmt; ++i) {
          SDValue Ops[] = {Result};
          Result = SDValue(CurDAG->getMachineNode(I8085::ASR_8, dl, MVT::i8, Ops), 0);
        }
        ReplaceUses(SDValue(N, 0), Result);
        CurDAG->RemoveDeadNode(N);
        return true;
      }
    }
    unsigned Opc=I8085::SRA_8;
    SDValue Ops[] = {LHS,RHS};
    SDNode *ResNode = CurDAG->getMachineNode(Opc, dl,MVT::i8,Ops);
    ReplaceUses(SDValue(N, 0), SDValue(ResNode, 0));
    CurDAG->RemoveDeadNode(N);
    return true;
  }

  return false;
}

